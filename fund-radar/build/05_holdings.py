def parse_cc(js):
    """返回 [(季度标签, [(code,name,pct)])]，按季度从新到旧
    列序（实测 2026-10-31）：0序号 1代码 2名称 3最新价 4涨跌幅 5相关资讯 6占净值比例 7持股数 8持仓市值
    ★ 不能靠"第一个百分比"取占比：涨跌幅列也是百分比，会串行。"""
    if not js:
        return []
    # 用 h4 标题切块
    marks = [(m.start(), m.group(1).strip()) for m in
             re.finditer(r'<h4[^>]*>.*?(\d{4}年\d季度)股票投资明细', js, re.S)]
    if not marks:
        return []
    out = []
    for i, (pos, label) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(js)
        seg = js[pos:end]
        rows, seen = [], set()
        for m in re.finditer(r'<tr[^>]*>(.*?)</tr>', seg, re.S):
            cells = [re.sub(r'<[^>]+>', '', c).strip() for c in
                     re.findall(r'<td[^>]*>(.*?)</td>', m.group(1), re.S)]
            if len(cells) < 7:
                continue
            code, nm, p = cells[1], cells[2], cells[6]
            if not code or not re.fullmatch(r'\d{5,6}', code):
                continue
            if code in seen:
                continue
            seen.add(code)
            mm = re.fullmatch(r'(\d+(?:\.\d+)?)%', p)
            if not mm:
                continue
            rows.append(dict(code=code, name=nm, pct=float(mm.group(1)), sector=classify(nm),
                             hk=(len(code) == 5)))
            if len(rows) >= 10:
                break
        out.append((label, rows))
    return out


def one(code):
    out = dict(code=code, quarters=[], cur=None, prev=None)
    for year, month in ((2026, 12), (2025, 12)):
        url = 'https://fundf10.eastmoney.com/FundArchivesDatas.aspx?type=jjcc&code=%s&topline=10&year=%d&month=%d' % (code, year, month)
        qs = parse_cc(get(url))
        if qs:
            out['quarters'] = [dict(label=l, list=rows) for l, rows in qs if rows]
            break
    return out


def main():
    sc = json.load(open(os.path.join(HERE, 'scored.json'), encoding='utf-8'))
    pool = sc['scored']
    targets = [f['code'] for f in pool[:55]]
    # 加上用户可能关注的：净值最强但没进榜的几只
    allf = sorted(sc['all'], key=lambda x: -(x['m']['r1y'] or -9))[:6]
    for f in allf:
        if f['code'] not in targets:
            targets.append(f['code'])
    print('抓取 %d 只基金的季报持仓' % len(targets))
    res = {}
    with ThreadPoolExecutor(max_workers=6) as ex:
        futs = {ex.submit(one, c): c for c in targets}
        for i, fu in enumerate(as_completed(futs)):
            r = fu.result()
            res[r['code']] = r
            if (i + 1) % 10 == 0:
                print('  ... %d/%d' % (i + 1, len(targets)), flush=True)
    ok = sum(1 for v in res.values() if v['quarters'])
    print('拿到持仓 %d / %d' % (ok, len(targets)))

    # 行业暴露
    for code, r in res.items():
        if not r['quarters']:
            continue
        lst = r['quarters'][0]['list']
        agg = {}
        for x in lst:
            agg[x['sector']] = agg.get(x['sector'], 0) + x['pct']
        r['expo'] = sorted([dict(sector=k, pct=round(v, 2)) for k, v in agg.items()], key=lambda x: -x['pct'])
        r['top10'] = round(sum(x['pct'] for x in lst), 2)
        r['q_label'] = r['quarters'][0]['label']

    json.dump(res, open(os.path.join(HERE, 'holdings.json'), 'w', encoding='utf-8'), ensure_ascii=False)

    # 交叉验证：净值相关性说的主战场 vs 持仓行业
    print('\n%-8s %-20s %-12s %-12s %s' % ('代码', '名称', '净值相关板块', '持仓最大行业', '一致性'))
    for f in pool[:14]:
        h = res.get(f['code'])
        if not h or not h.get('expo'):
            print('%-8s %-20s %-12s %-12s %s' % (f['code'], f['name'][:18], f['main_sector'], '无数据', '-'))
            continue
        top = h['expo'][0]['sector']
        tags = [e['sector'] for e in h['expo'][:3]]
        hit = f['main_sector'] in tags
        print('%-8s %-20s %-12s %-12s %s' % (f['code'], f['name'][:18], f['main_sector'], top,
                                             '一致' if hit else '不一致 -> 持仓: ' + '/'.join(tags)))
    print('\n-> holdings.json')


main()
